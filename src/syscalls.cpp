// Заглушки системных вызовов newlib. Файлов и консоли у нас нет,
// а куча не используется (new и malloc нигде не вызываются).
#include <cerrno>
#include <sys/stat.h>

extern "C" {

/*
 * Заглушка newlib: закрыть файл. Файлов нет, поэтому всегда ошибка.
 *
 * Параметры:
 *   fd — номер файла (не используется).
 *
 * Возвращает: -1, errno = EBADF.
 */
int _close(int)
{
    errno = EBADF;
    return -1;
}

/*
 * Заглушка newlib: сведения о файле. Сообщает, что любой файл — символьное
 * устройство (терминал), тогда stdio не будет буферизовать его как файл.
 *
 * Параметры:
 *   fd — номер файла (не используется);
 *   st — куда записать сведения; заполняется только st_mode.
 *
 * Возвращает: 0.
 */
int _fstat(int, struct stat *st)
{
    st->st_mode = S_IFCHR;
    return 0;
}

/*
 * Заглушка newlib: является ли файл терминалом.
 *
 * Параметры:
 *   fd — номер файла (не используется).
 *
 * Возвращает: всегда 1.
 */
int _isatty(int)
{
    return 1;
}

/*
 * Заглушка newlib: перемещение по файлу. Ничего не делает.
 *
 * Параметры:
 *   fd     — номер файла (не используется);
 *   off    — смещение (не используется);
 *   whence — откуда отсчитывать смещение (не используется).
 *
 * Возвращает: всегда 0.
 */
int _lseek(int, int, int)
{
    return 0;
}

/*
 * Заглушка newlib: чтение из файла (stdin). Ввода нет.
 *
 * Параметры:
 *   fd  — номер файла (не используется);
 *   buf — куда читать (не используется);
 *   len — сколько байт читать (не используется).
 *
 * Возвращает: 0 — конец файла.
 */
int _read(int, char *, int)
{
    return 0;
}

/*
 * Заглушка newlib: запись в файл (stdout/stderr). Данные выбрасываются:
 * лог пишется напрямую в UART через logger::print(), а не через printf.
 *
 * Параметры:
 *   fd  — номер файла (не используется);
 *   buf — данные (не используются);
 *   len — сколько байт записать.
 *
 * Возвращает: len — «всё записано».
 */
int _write(int, const char *, int len)
{
    return len;
}

/*
 * Заглушка newlib: номер процесса. Процесс один.
 * Параметров нет.
 *
 * Возвращает: всегда 1.
 */
int _getpid()
{
    return 1;
}

/*
 * Заглушка newlib: послать сигнал процессу. Сигналов нет.
 *
 * Параметры:
 *   pid — номер процесса (не используется);
 *   sig — номер сигнала (не используется).
 *
 * Возвращает: -1, errno = EINVAL.
 */
int _kill(int, int)
{
    errno = EINVAL;
    return -1;
}

/*
 * Заглушка newlib: завершение программы (например, из abort()). Завершаться
 * некуда, поэтому зависает; сторожевой таймер перезагрузит плату.
 *
 * Параметры:
 *   status — код завершения (не используется).
 */
void _exit(int)
{
    for (;;) {
    }
}

/*
 * Заглушка newlib: выделить память под кучу. Куча не используется,
 * и если какая-то функция библиотеки всё же попросит память, она получит
 * отказ, а не испортит стек.
 *
 * Параметры:
 *   incr — на сколько байт увеличить кучу (не используется).
 *
 * Возвращает: (void *)-1, errno = ENOMEM.
 */
void *_sbrk(int)
{
    errno = ENOMEM;
    return reinterpret_cast<void *>(-1);
}

} // extern "C"
